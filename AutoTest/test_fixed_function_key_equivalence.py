"""Pure fake-process red-team tests for the FF equivalence orchestration.

The production runner is imported unchanged, but its sole Desktop/process
authority is replaced by a fake. Temporary .exe files are inert text and PE
inspection is mocked; no native process, Desktop, GPU, DLL or game is used.
Generated bytes are fixture data, not proof of a valid shader or rendering.
The census parser has its own tests and is stubbed here to isolate the runner.

Run: python -B AutoTest/test_fixed_function_key_equivalence.py
"""

